public class Calculadora {
    public static int resultaSoma(int a, int b){
        return a + b;
    }

    public static int resultaSub(int a, int b){
        return a - b;
    }

    public static int resultaMulti(int a, int b){
        return a * b;
    }

    public static int resultaDivi(int a, int b){
        return a / b;
    }
}
